import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const sourceRoot = resolve(root, 'src')
const outputPath = resolve(sourceRoot, 'icons', 'mdiSubset.ts')
const collection = JSON.parse(await readFile(resolve(root, 'node_modules/@iconify-json/mdi/icons.json'), 'utf8'))

async function sourceFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true })
  const nested = await Promise.all(entries.map(async (entry) => {
    const path = resolve(directory, entry.name)
    if (entry.isDirectory()) return sourceFiles(path)
    return /\.(?:ts|vue)$/.test(entry.name) && path !== outputPath ? [path] : []
  }))
  return nested.flat()
}

const names = new Set()
for (const file of await sourceFiles(sourceRoot)) {
  const source = await readFile(file, 'utf8')
  for (const match of source.matchAll(/mdi:([a-z0-9-]+)/g)) names.add(match[1])
}

const icons = {}
const aliases = {}
const missing = []
function include(name) {
  if (collection.icons[name]) {
    icons[name] = collection.icons[name]
    return
  }
  const alias = collection.aliases?.[name]
  if (!alias) { missing.push(name); return }
  aliases[name] = alias
  include(alias.parent)
}
for (const name of [...names].sort()) include(name)
if (missing.length) throw new Error(`Icon MDI tidak ditemukan:\n${[...new Set(missing)].map((name) => `- mdi:${name}`).join('\n')}`)

const subset = {
  prefix: collection.prefix,
  width: collection.width,
  height: collection.height,
  icons: Object.fromEntries(Object.entries(icons).sort(([left], [right]) => left.localeCompare(right))),
  ...(Object.keys(aliases).length ? { aliases: Object.fromEntries(Object.entries(aliases).sort(([left], [right]) => left.localeCompare(right))) } : {}),
}
const generated = `// Generated by scripts/generate-icon-subset.mjs. Do not edit manually.\nimport type { IconifyJSON } from '@iconify/vue'\n\nexport const mdiSubset = ${JSON.stringify(subset, null, 2)} satisfies IconifyJSON\n`

if (process.argv.includes('--check')) {
  const current = await readFile(outputPath, 'utf8').catch(() => '')
  if (current !== generated) {
    console.error('Subset ikon MDI tidak sinkron. Jalankan: npm run icons:generate')
    process.exitCode = 1
  }
} else {
  await mkdir(resolve(sourceRoot, 'icons'), { recursive: true })
  await writeFile(outputPath, generated)
  console.log(`Generated ${Object.keys(icons).length} MDI icons and ${Object.keys(aliases).length} aliases.`)
}
